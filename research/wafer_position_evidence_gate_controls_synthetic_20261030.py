"""Small in-memory connection experiment: synthetic rows -> analyzer -> evidence gate.

Research-only demonstration. It does not represent model performance,
calibration, actual wafer behavior, or a field false-alarm estimate.
"""
from __future__ import annotations

import argparse
import json
from typing import Any

from research.wafer_class_position_controls_synthetic_20261030 import (
    ALPHA, PLANNED_CLASSES, SCENARIOS, _generation_seed, generate_rows,
)
from research.wafer_defect_class_position_20261030 import analyze_defect_class_positions
from research.wafer_position_evidence_gate_synthetic_20261030 import assess_spatial_evidence

ESTIMANDS = ("classified_inspected_die_occurrence", "within_classified_fail_composition")
DEFAULT_SEEDS = (42,)
PERMUTATIONS = 99


def run_one(scenario: str, seed: int, permutations: int = PERMUTATIONS) -> dict[str, Any]:
    if scenario not in SCENARIOS:
        raise ValueError(f"unknown scenario: {scenario}")
    if permutations < 99:
        raise ValueError("permutations must be >= 99")
    rows = generate_rows(scenario, seed)
    label_independent = scenario != "selective_center_a_rejection"
    # The selective-rejection design omits center A outcomes, so coverage of
    # the target class is not adequate even though every synthetic die was
    # inspected and geometrically represented.
    coverage_adequate = scenario != "selective_center_a_rejection"
    # Assertion truth is disclosed alongside the actual analyzer/gate inputs.
    analysis = analyze_defect_class_positions(
        rows, PLANNED_CLASSES,
        labeler_position_independent_asserted=label_independent,
        permutations=permutations, seed=seed, alpha=ALPHA,
    )
    gates = []
    for estimand in ESTIMANDS:
        for class_id in PLANNED_CLASSES:
            gate = assess_spatial_evidence(
                analysis, class_id=class_id, estimand=estimand, alpha=ALPHA,
                labeler_position_independent_asserted=label_independent,
                geometry_validated_asserted=True,
                coverage_adequate_asserted=coverage_adequate,
                null_assumptions_accepted_asserted=label_independent,
            )
            result = analysis.get("estimands", {}).get(estimand, {}).get("class_results", {}).get(class_id, {})
            gates.append({
                "estimand": estimand, "class_id": class_id,
                "raw_p_value": result.get("raw_p_value"),
                "holm_adjusted_p_value": result.get("holm_adjusted_p_value"),
                "analyzer_status": result.get("status"),
                "holm_reject": result.get("holm_reject"),
                "gate_status": gate["status"], "gate_reason": gate["reason"],
                "eligible_for_asserted_frozen_spatial_weight": gate["eligible_for_asserted_frozen_spatial_weight"],
                "denominator_by_radial_bin": result.get("classified_die_denominator_by_radial_bin"),
                "target_class_count_by_radial_bin": result.get("target_class_count_by_radial_bin"),
            })
    return {
        "scenario": scenario, "seed": seed, "generation_rng_seed": _generation_seed(seed),
        "permutations": permutations, "alpha": ALPHA, "synthetic_only": True,
        "inference_authoritative": False,
        "input_row_count": len(rows), "coverage": analysis["coverage"],
        "assertions": {
            "labeler_position_independent_asserted_input": label_independent,
            "label_independence_assertion_truthful_by_design": label_independent,
            "geometry_validated_asserted": True,
            "coverage_adequate_asserted": coverage_adequate,
            "null_assumptions_accepted_asserted": label_independent,
            "geometry_basis": "fixed synthetic normalized grid generated by existing control module",
            "coverage_basis": "scenario 5 has position/class-dependent A rejection, so A coverage is inadequate despite every generated row having valid coordinates and completed inspection; other scenarios have no designed selective rejection",
        },
        "estimand_denominators": {
            "classified_inspected_die_occurrence": analysis["coverage"]["classified_inspected_die_denominator_by_radial_bin"],
            "within_classified_fail_composition": analysis["coverage"]["confirmed_known_fail_denominator_by_radial_bin"],
        },
        "results": gates,
        "interpretation_limits": [
            "A non-significant result is not proof of no association, randomness, or position independence.",
            "Five or fewer small synthetic seed runs are not an error-rate estimate.",
            "No model performance or calibration is measured; gate eligibility only reflects supplied assertions and synthetic analyzer output.",
            "Selective rejection violates label-independent eligibility; its inferential results are unavailable through the analyzer assertion path and the gate reports missing_result.",
        ],
    }


def run_experiment(seeds: tuple[int, ...] = DEFAULT_SEEDS, permutations: int = PERMUTATIONS) -> dict[str, Any]:
    if not seeds:
        raise ValueError("at least one seed is required")
    runs = [run_one(scenario, seed, permutations) for scenario in SCENARIOS for seed in seeds]
    return {
        "experiment": "wafer-position-evidence-gate-controls-synthetic-20261030",
        "scenario_count": len(SCENARIOS), "seed_count": len(seeds),
        "run_count": len(runs), "seeds": list(seeds), "permutations": permutations,
        "runs": runs,
        "interpretation_limits": [
            "Synthetic in-memory reproduction only; no files, actual wafer data, or model outputs are used.",
            "Statistical non-significance does not establish no association.",
            "Small repeated runs characterize these constructed examples only and do not estimate error rates.",
            "No model performance or calibration claim is made.",
        ],
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", type=int, nargs="+", default=list(DEFAULT_SEEDS))
    parser.add_argument("--permutations", type=int, default=PERMUTATIONS)
    args = parser.parse_args()
    print(json.dumps(run_experiment(tuple(args.seeds), args.permutations), indent=2, sort_keys=True))
