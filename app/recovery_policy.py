_ADVICE = {
    'scope_identity': ('reacquire_scope_or_clarify', True,
                       'Return to Router for authorized scope reacquisition or explicit selection; preserve scope and as_of bounds.'),
    'model_contract': ('correct_full_contract', True,
                       'Correct the output using the full role contract within existing budgets; preserve failed business Tool code_gate.'),
    'configuration_schema': ('verified_mapping_diagnostics', False,
                             'Stop for verified configuration/schema diagnostics and an offline fix; never guess tables, columns or joins.'),
    'transport_unavailable': ('stop_and_propagate', False,
                            'Propagate unavailability under the existing policy; do not broaden queries or retry writes.'),
    'action_reconciliation': ('adapter_reconciliation', False,
                              'Stop for Adapter reconciliation and approval state verification; never retry an action with unknown commit state.'),
    'unknown': ('bounded_router_review', True,
                'Use existing bounded Router review only; preserve rights, scope, evidence and failed business Tool code_gate.'),
}


def classify_recovery(error, error_type=None):
    """Classify a trusted runtime exception/code into finite, non-executing advice.

    error_type may be an exception class or its name when runtime sanitizes the
    original exception. Neither this function nor its advice grants a retry;
    the caller retains existing retry/call budgets and dispatch policy.
    """
    kind = error_type or type(error)
    kind = kind.__name__ if isinstance(kind, type) else kind
    raw_code = str(error).partition(':')[0].strip()
    known = _SCOPE | _CONFIG | _CONTRACT | _STOP
    code = raw_code if raw_code in known else None
    if raw_code.startswith(('ACTION_', 'COMMIT_')) or raw_code in ('UNKNOWN_COMMIT', 'UNKNOWN_COMMIT_STATE', 'UNKNOWN_ACTION_COMMIT_STATE'):
        category, code = 'action_reconciliation', 'ACTION_OR_COMMIT_FAILURE'
    elif code in _SCOPE:
        category = 'scope_identity'
    elif code in _CONFIG or kind == 'ConfigError':
        category = 'configuration_schema'
    elif code in _STOP or kind in ('TimeoutError', 'ConnectionError', 'HTTPError', 'URLError', 'PermissionError'):
        category = 'transport_unavailable'
    elif code in _CONTRACT or kind == 'JSONDecodeError':
        category = 'model_contract'
    else:
        category = 'unknown'
    action, via_router, guidance = _ADVICE[category]
    return {'category': category, 'action': action, 'error_code': code,
            'force_full_context': True, 'retry_via_router': via_router,
            'automatic_tool_retry': False, 'write_retry_allowed': False,
            'preserve_code_gate': True, 'preserve_evidence': True,
            'respect_existing_budgets': True, 'guidance': guidance}
